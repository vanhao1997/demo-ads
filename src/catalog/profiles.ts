export function resolveProfile(profileId: string): Profile | undefined {
  const normalizedId =
    profileId === 'tiktok.in_feed.video' || profileId === 'tiktok.in_feed.standard_carousel'
      ? 'tiktok.in_feed'
      : profileId

  // 1. Direct match in canonical AD_PROFILES
  const canonical = AD_PROFILES.find((profileItem) => profileItem.id === normalizedId)
  if (canonical) return canonical

  // 2. Direct match in LEGACY_PROFILES
  const legacy = LEGACY_PROFILES.find((profileItem) => profileItem.id === normalizedId)
  if (legacy) return legacy

  // 3. Alias resolution
  const targetId = PROFILE_ALIASES[normalizedId]
  if (targetId) {
    const fromAlias =
      AD_PROFILES.find((profileItem) => profileItem.id === targetId) ??
      LEGACY_PROFILES.find((profileItem) => profileItem.id === targetId)
    if (fromAlias) return fromAlias
  }

  // 4. Fallback to admicro dynamic slots/packages
  return resolveAdmicroProfile(normalizedId)
}

export function requireProfile(profileId: string): Profile {
  const found = resolveProfile(profileId)
  if (!found) throw new Error(`Unknown ad profile: ${profileId}`)
  return found
}

export function profilesByGroup(groupId: PlatformGroupId): Profile[] {
  return AD_PROFILES.filter((profileItem) => profileItem.groupId === groupId)
}

