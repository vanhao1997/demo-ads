type RuleInit = Omit<ValidationRule, 'ruleId' | 'severity' | 'evidence' | 'sourceRefs'> & {
  id: string
  severity?: ValidationRule['severity']
  evidence?: EvidenceLevel
  sourceRefs?: SourceRefId[]
}

function rule(
  init: RuleInit,
  defaultSourceRefs: SourceRefId[],
  defaultEvidence: EvidenceLevel,
): ValidationRule {
  return {
    ruleId: init.id,
    fieldPath: init.fieldPath,
    operator: init.operator,
    expected: init.expected,
    severity: init.severity ?? 'fail',
    message: init.message,
    sourceRefs: init.sourceRefs ?? defaultSourceRefs,
    evidence: init.evidence ?? defaultEvidence,
    confidence: init.confidence,
    scope: init.scope,
    each: init.each,
    countingStrategy: init.countingStrategy,
    whenComposition: init.whenComposition,
    notes: init.notes,
  }
}

function textMax(
  fieldPath: string,
  max: number,
  message: string,
  options: Partial<RuleInit> = {},
): RuleInit {
  return {
    id: `${fieldPath}.max_${max}`.replace(/[^a-z0-9_.-]/gi, '_'),
    fieldPath,
    operator: 'maxLength',
    expected: max,
    countingStrategy: options.countingStrategy ?? 'grapheme',
    message,
    ...options,
  }
}

function textMin(
  fieldPath: string,
  min: number,
  message: string,
  options: Partial<RuleInit> = {},
): RuleInit {
  return {
    id: `${fieldPath}.min_${min}`.replace(/[^a-z0-9_.-]/gi, '_'),
    fieldPath,
    operator: 'minLength',
    expected: min,
    countingStrategy: options.countingStrategy ?? 'grapheme',
    message,
    ...options,
  }
}

function countRange(
  fieldPath: string,
  min: number,
  max: number,
  message: string,
  options: Partial<RuleInit> = {},
): RuleInit[] {
  return [
    {
      id: `${fieldPath}.min_count_${min}`.replace(/[^a-z0-9_.-]/gi, '_'),
      fieldPath,
      operator: 'minCount',
      expected: min,
      message,
      ...options,
    },
    {
      id: `${fieldPath}.max_count_${max}`.replace(/[^a-z0-9_.-]/gi, '_'),
      fieldPath,
      operator: 'maxCount',
      expected: max,
      message,
      ...options,
    },
  ]
}

function assetCount(
  min: number,
  max: number,
  message: string,
  compositions?: CompositionKind[],
): RuleInit[] {
  return [
    {
      id: `assets.min_count_${min}`,
      fieldPath: 'composition.assetIds',
      operator: 'minCount',
      expected: min,
      message,
      whenComposition: compositions,
    },
    {
      id: `assets.max_count_${max}`,
      fieldPath: 'composition.assetIds',
      operator: 'maxCount',
      expected: max,
      message,
      whenComposition: compositions,
    },
  ]
}

function mediaRules(
  kind: 'image' | 'video' | 'audio',
  mimes: string[],
  options: Partial<RuleInit> = {},
): RuleInit[] {
  return [
    {
      id: `asset.kind.${kind}`,
      fieldPath: 'assets.kind',
      operator: 'allowedValues',
      expected: [kind],
      scope: 'all_assets',
      each: true,
      message: `Asset phai la ${kind}.`,
      ...options,
    },
    {
      id: `asset.mime.${kind}`,
      fieldPath: 'assets.mime',
      operator: 'mimeIn',
      expected: mimes,
      scope: 'all_assets',
      each: true,
      message: `Dinh dang ${kind} khong nam trong profile.`,
      ...options,
    },
  ]
}

function imageRules(
  options: Partial<RuleInit> = {},
  mimes = ['image/jpeg', 'image/png'],
): RuleInit[] {
  return mediaRules('image', mimes, options)
}

function videoRules(options: Partial<RuleInit> = {}): RuleInit[] {
  return [
    ...mediaRules('video', ['video/mp4'], options),
    {
      id: 'asset.codec.h264',
      fieldPath: 'assets.codec',
      operator: 'codecIn',
      expected: ['h264', 'avc1'],
      scope: 'all_assets',
      each: true,
      message:
        'Video can xac minh H.264/AVC. Neu browser doc duoc MP4 van chua du bang chung codec.',
      ...options,
    },
  ]
}

function urlRule(options: Partial<RuleInit> = {}): RuleInit {
  return {
    id: 'copy.destinationUrl.http',
    fieldPath: 'copy.destinationUrl',
    operator: 'url',
    expected: ['http:', 'https:'],
    message: 'Destination URL phai dung HTTP(S).',
    ...options,
  }
}

function profile(init: {
  id: string
  groupId: PlatformGroupId
  platform?: PlatformId
  product: AdProductId
  productLabel: string
  surface: string
  placement: string
  device: DeviceClass
  renderer: RendererKind
  allowedCompositions: CompositionKind[]
  sourceRefs: SourceRefId[]
  evidence: EvidenceLevel
  confidence?: Confidence
  rules?: RuleInit[]
  notes?: string[]
}): Profile {
  const group = PLATFORM_GROUPS.find((item) => item.id === init.groupId)
  if (!group) throw new Error(`Missing platform group ${init.groupId}`)
  const rules = (init.rules ?? []).map((item) => rule(item, init.sourceRefs, init.evidence))
  return {
    id: init.id,
    groupId: init.groupId,
    groupTitle: group.title,
    platform: init.platform ?? group.platform,
    product: init.product,
    productLabel: init.productLabel,
    surface: init.surface,
    placement: init.placement,
    device: init.device,
    renderer: init.renderer,
    allowedCompositions: init.allowedCompositions,
    supportStatus:
      init.evidence === 'unknown' || init.evidence === 'conflict' ? 'needs_review' : 'active',
    implementation: 'implemented',
    evidence: init.evidence,
    confidence:
      init.confidence ??
      (init.evidence === 'primary_documented'
        ? 'high'
        : init.evidence === 'conflict'
          ? 'low'
          : 'medium'),
    sourceRefs: init.sourceRefs,
    sources: resolveSources(init.sourceRefs),
    specVersion: CATALOG_VERSION,
    effectiveAt: null,
    checkedAt: SOURCE_CHECKED_AT,
    rules,
    fieldRules: rules,
    notes: init.notes,
  }
}

